/** Presentation only: application commands enforce authority and last-active-admin safety. */
export function authorityConfirmation(input: {
  isHospitalAdmin: boolean;
  isActive: boolean;
  self: boolean;
}) {
  const removing = input.isHospitalAdmin;
  return {
    title: removing ? "حذف نقش مدیر بیمارستان" : "اعطای نقش مدیر بیمارستان",
    removing,
    warning: removing && input.self,
    description: removing
      ? input.self
        ? "شما در حال حذف اختیار مدیریتی خود هستید. پس از تأیید، به صفحه مجاز خود منتقل می‌شوید و کنترل‌های مدیریت بیمارستان دیگر در دسترس شما نیستند. این کار فقط اگر مدیر فعال دیگری باقی بماند مجاز است."
        : "اختیار مدیریت کاربران و دسترسی‌های بیمارستان از این کاربر گرفته می‌شود. حساب، عضویت‌های بخش و دسترسی‌های سوپروایزر تغییر نمی‌کنند. آخرین مدیر فعال باید باقی بماند."
      : input.isActive
        ? "این کاربر اختیار مدیریت کاربران و دسترسی‌های بیمارستان را دریافت می‌کند. این نقش سیستمی مستقل از عضویت بخش و نظارت است و مجوز ویرایش یا تأیید برنامه‌های بخش را به‌تنهایی نمی‌دهد."
        : "این حساب غیرفعال است. نقش مدیریتی ذخیره می‌شود اما تا فعال‌سازی صریح حساب هیچ دسترسی یا امکان ورود نمی‌دهد. اعطای نقش، حساب را فعال نمی‌کند و عضویت‌ها یا نظارت‌ها را تغییر نمی‌دهد.",
  };
}
